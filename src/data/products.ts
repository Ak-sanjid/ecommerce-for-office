export const topSelling = products.filter((p) => p.isTopSelling);
export const todaysOffer = products.filter((p) => p.isTodayOffer);
export const flashSaleProducts = products.filter((p) => p.flashSale);

export function getProduct(idOrSlug: string): Product | undefined {
  return products.find((p) => p.id === idOrSlug || slugify(p.name) === idOrSlug);
}

export function slugify(name: string): string {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");
}

export function relatedTo(p: Product, n = 8): Product[] {
  return products
    .filter((x) => x.id !== p.id)
    .sort((a, b) => {
      const sa = (a.brand === p.brand ? 3 : 0) + (a.category === p.category ? 2 : 0) + (a.origin === p.origin ? 1 : 0);
      const sb = (b.brand === p.brand ? 3 : 0) + (b.category === p.category ? 2 : 0) + (b.origin === p.origin ? 1 : 0);
      return sb - sa;
    })
    .slice(0, n);
}
